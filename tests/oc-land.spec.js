import { test, expect } from '@playwright/test'

test('land card opens supplied property with gallery, videos, contacts and return', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.route('https://www.youtube-nocookie.com/**', route => route.fulfill({ contentType: 'text/html', body: '<html><body>Video fixture</body></html>' }))
  await page.goto('/')
  await expect(page).toHaveURL(/\/oc$/)
  await expect(page.locator('#architecture')).toHaveAttribute('data-scene', '0')
  await page.locator('nav a[href="#propiedades"]').click()
  await page.locator('[data-type="terreno"]').click()
  await expect(page).toHaveURL(/\/oc\/propiedades\/terreno-villa-nueva$/)
  await expect(page.locator('.oc-land-page')).toBeVisible()
  await page.reload()
  await expect(page.locator('.oc-land-page')).toBeVisible()
  await expect(page.locator('.oc-page')).not.toBeVisible()
  await expect(page.locator('#land-title')).toHaveText('Imagina lo que viene.')
  await expect(page.locator('.land-stats')).toContainText('9,911.56')
  await expect(page.locator('.land-stats')).toContainText('149')
  await expect.poll(() => page.locator('.hero-photo.is-active').evaluate(image => image.naturalWidth)).toBeGreaterThan(0)
  await page.screenshot({ path: 'test-results/oc-land-desktop.png' })
  await page.locator('.land-header a[href="#land-gallery"]').click()
  await page.locator('#land-gallery').getByRole('button', { name: 'Terreno despejado', exact: true }).click()
  await expect(page.locator('.gallery-photo img')).toHaveAttribute('src', /cleared-3.webp/)
  await expect(page.locator('.concept-badge')).toHaveText('CONCEPTO VISUAL')
  await page.getByRole('button', { name: 'Fotografía siguiente', exact: true }).click()
  await expect(page.locator('.photo-counter')).toHaveText('04 / 06')
  await page.getByRole('button', { name: 'Ampliar fotografía del terreno' }).click()
  await expect(page.locator('.land-lightbox')).toBeVisible()
  await page.keyboard.press('ArrowRight')
  await expect(page.locator('.lightbox-bar')).toContainText('5 / 6')
  await page.keyboard.press('Escape')
  await expect(page.locator('.land-lightbox')).not.toBeVisible()
  await page.screenshot({ path: 'test-results/oc-land-gallery.png' })
  await page.locator('.land-header a[href="#land-videos"]').click()
  await page.getByRole('button', { name: 'Reproducir video del terreno' }).click()
  await expect(page.locator('.video-frame iframe')).toHaveAttribute('src', /bOfYyESV2pM/)
  await page.getByRole('button', { name: 'Video siguiente', exact: true }).click()
  await expect(page.locator('.video-frame iframe')).toHaveCount(0)
  await expect(page.locator('#land-videos')).toContainText('Recorrido general del terreno')
  await expect(page.locator('.contact-options a').first()).toHaveAttribute('href', /^https:\/\/wa.me\/50242390413\?text=/)
  await expect(page.locator('.contact-options a').last()).toHaveAttribute('href', /^https:\/\/wa.me\/50253684955\?text=/)
  await expect(page.locator('.location-reference a')).toHaveAttribute('href', 'https://www.google.com/maps?q=14.500054890872207,-90.57174869986984')
  await page.locator('.land-header a[href="#land-location"]').click()
  await expect(page.locator('.location-map iframe')).toHaveAttribute('src', 'https://www.google.com/maps?q=14.500054890872207,-90.57174869986984&z=16&output=embed')
  await expect(page.locator('.location-map iframe')).toBeVisible()
  await page.waitForTimeout(2500)
  await page.screenshot({ path: 'test-results/oc-land-map.png' })
  await page.locator('.oc-land-page ion-content').evaluate(async el => { const scroll = await el.getScrollElement(); scroll.scrollTop = scroll.scrollHeight })
  await page.locator('.land-footer button').click()
  await expect(page).toHaveURL(/\/oc\?section=propiedades/)
  await expect(page.locator('.oc-page')).toBeVisible()
  await expect(page.locator('.oc-page #chapter-number')).toHaveText('03 / 04')
  expect(errors).toEqual([])
})

test('land detail is directly addressable and usable on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/oc/propiedades/terreno-villa-nueva')
  await expect(page).toHaveTitle(/El Cortijo/)
  await expect(page.locator('.land-logo img')).toBeVisible()
  await page.screenshot({ path: 'test-results/oc-land-mobile.png' })
  await page.locator('.land-menu').click()
  await page.locator('.land-header a[href="#land-gallery"]').click()
  await expect(page.locator('.land-menu')).toHaveAttribute('aria-expanded', 'false')
  await page.getByRole('button', { name: 'Frente del terreno', exact: true }).click()
  await expect(page.locator('.photo-counter')).toHaveText('06 / 06')
  await page.screenshot({ path: 'test-results/oc-land-mobile-gallery.png' })
  const overflow = await page.locator('.oc-land-page ion-content').evaluate(async el => {
    const scroll = await el.getScrollElement()
    return scroll.scrollWidth > scroll.clientWidth
  })
  expect(overflow).toBe(false)
  await page.locator('.land-menu').click()
  await page.locator('.land-header a[href="#land-location"]').click()
  await expect(page.locator('.location-map iframe')).toBeVisible()
  expect(await page.locator('.location-map').evaluate(el => el.getBoundingClientRect().right <= innerWidth)).toBe(true)
})

test('hero automatically cycles original photos, switches modes, and pauses offscreen', async ({ page }) => {
  await page.goto('/oc/propiedades/terreno-villa-nueva')
  const hero = page.locator('.land-hero-carousel')
  await expect(hero.locator('.hero-photo')).toHaveCount(12)
  await expect(hero).toHaveAttribute('data-mode', 'actual')
  await expect(hero).toHaveAttribute('data-index', '1', { timeout: 7000 })
  await hero.locator('.hero-playback').click()
  const pausedIndex = await hero.getAttribute('data-index')
  await page.waitForTimeout(2700)
  await expect(hero).toHaveAttribute('data-index', pausedIndex)
  await hero.getByRole('button', { name: 'Terreno despejado', exact: true }).click()
  await expect(hero).toHaveAttribute('data-index', '0')
  await expect(hero.locator('.hero-photo.is-active')).toHaveAttribute('src', /cleared-1.webp/)
  await expect(hero.locator('.hero-state-caption')).toContainText('Concepto visual')
  await hero.getByRole('button', { name: 'Estado actual', exact: true }).click()
  await hero.getByRole('button', { name: 'Portada: Frente del terreno', exact: true }).click()
  await expect(hero).toHaveAttribute('data-index', '5')
  await hero.locator('.hero-playback').click()
  await expect(hero).toHaveAttribute('data-mode', 'cleared', { timeout: 5000 })
  await expect(hero).toHaveAttribute('data-index', '0')
  await page.locator('.land-header a[href="#land-gallery"]').click()
  await expect.poll(() => hero.evaluate(el => el.getBoundingClientRect().bottom)).toBeLessThan(0)
  const offscreenIndex = await hero.getAttribute('data-index')
  await page.waitForTimeout(2800)
  await expect(hero).toHaveAttribute('data-index', offscreenIndex)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(hero.locator('.hero-playback')).toHaveAttribute('aria-pressed', 'false')
})
