import { test, expect } from '@playwright/test'

test('OC cinematic preview: camera, gallery, consultation and mobile', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/oc')
  await expect(page).toHaveTitle(/OC Grupo Inmobiliario/)
  await expect(page.locator('ion-app ion-content')).toBeVisible()
  await expect(page.locator('#architecture')).toHaveAttribute('data-scene', '0')
  await page.screenshot({ path: 'test-results/oc-ionic-desktop.png' })
  await page.locator('#play').click()
  await expect.poll(() => page.locator('ion-content').evaluate(async el => (await el.getScrollElement()).scrollTop)).toBeGreaterThan(10)
  await page.locator('#play').click()
  const stopped = await page.locator('ion-content').evaluate(async el => (await el.getScrollElement()).scrollTop)
  await page.waitForTimeout(150)
  expect(await page.locator('ion-content').evaluate(async el => (await el.getScrollElement()).scrollTop)).toBe(stopped)
  await page.locator('nav a[href="#nosotros"]').click()
  await expect(page.locator('#architecture')).toHaveAttribute('data-scene', '1')
  await page.screenshot({ path: 'test-results/oc-ionic-nosotros.png' })
  await page.locator('nav a[href="#propiedades"]').click()
  await expect(page.locator('#chapter-number')).toHaveText('03 / 04')
  await page.locator('[data-filter="terreno"]').click()
  await expect(page.locator('.property:visible')).toHaveCount(1)
  await expect(page.locator('.property:visible')).toContainText('El Cortijo')
  await page.locator('[data-filter="casa"]').click()
  await page.locator('.property:visible').first().click()
  await expect(page.locator('dialog')).toBeVisible()
  await page.locator('#ask-property').click()
  await expect(page.locator('[name="mensaje"]')).toHaveValue(/Casa con jardín/)
  await expect(page.locator('#chapter-number')).toHaveText('04 / 04')
  await page.locator('[name="nombre"]').fill('Prueba OC')
  await page.locator('[name="correo"]').fill('prueba@example.com')
  const download = page.waitForEvent('download')
  await page.locator('form button').click()
  expect((await download).suggestedFilename()).toBe('consulta-grupo-oc.txt')
  await expect(page.locator('#form-status')).toContainText('No se ha enviado')
  await page.screenshot({ path: 'test-results/oc-ionic-contacto.png' })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.locator('#play')).toBeDisabled()
  await page.locator('nav a[href="#inicio"]').click()
  await expect(page.locator('#architecture')).toHaveAttribute('data-progress', '0.0000')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('.menu-toggle')).toBeVisible()
  await page.screenshot({ path: 'test-results/oc-ionic-mobile.png' })
  expect(await page.locator('ion-content').evaluate(async el => { const scroll = await el.getScrollElement(); return scroll.scrollWidth <= scroll.clientWidth })).toBe(true)
  await page.locator('.menu-toggle').click()
  await expect(page.locator('.menu-toggle')).toHaveAttribute('aria-expanded', 'true')
  await page.locator('nav a[href="#propiedades"]').click()
  await expect(page.locator('.menu-toggle')).toHaveAttribute('aria-expanded', 'false')
  await page.locator('[data-filter="all"]').click()
  await page.screenshot({ path: 'test-results/oc-ionic-mobile-gallery.png' })
  expect(await page.locator('ion-content').evaluate(async el => { const scroll = await el.getScrollElement(); return scroll.scrollWidth <= scroll.clientWidth })).toBe(true)
  expect(errors).toEqual([])
})

test('OC facade stays continuous through chapter boundaries in both directions', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/oc')
  const canvas = page.locator('#architecture')
  await expect(canvas).toHaveAttribute('data-camera-y', '0.000')
  const boundaries = await page.locator('.chapter').evaluateAll(nodes => nodes.slice(1).map(node => node.offsetTop))
  for (const boundary of boundaries) {
    await page.locator('ion-content').evaluate(async (el, y) => { (await el.getScrollElement()).scrollTop = y }, boundary - 2)
    await page.waitForTimeout(60)
    const before = await canvas.evaluate(node => ({ y: Number(node.dataset.cameraY), scale: node.dataset.cameraScale }))
    await page.locator('ion-content').evaluate(async (el, y) => { (await el.getScrollElement()).scrollTop = y }, boundary + 2)
    await page.waitForTimeout(60)
    const after = await canvas.evaluate(node => ({ y: Number(node.dataset.cameraY), scale: node.dataset.cameraScale }))
    expect(after.scale).toBe(before.scale)
    expect(after.y).toBeLessThan(before.y)
    expect(Math.abs(after.y - before.y)).toBeLessThan(15)
    await page.locator('ion-content').evaluate(async (el, y) => { (await el.getScrollElement()).scrollTop = y }, boundary - 2)
    await page.waitForTimeout(60)
    expect(Number(await canvas.getAttribute('data-camera-y'))).toBe(before.y)
  }
})

test('OC stops playback on route leave and resumes navigation after cached return', async ({ page }) => {
  await page.goto('/oc')
  const canvas = page.locator('.oc-page #architecture')
  await expect(canvas).toHaveAttribute('data-scene', '0')
  await page.locator('#play').click()
  await expect.poll(() => canvas.getAttribute('data-camera-y')).not.toBe('0.000')
  await page.evaluate(() => document.querySelector('#app').__vue_app__.config.globalProperties.$router.push('/oc/propiedades/terreno-villa-nueva'))
  await expect(page.locator('.oc-land-page')).toBeVisible()
  const frozen = await canvas.getAttribute('data-camera-y')
  await page.waitForTimeout(200)
  expect(await canvas.getAttribute('data-camera-y')).toBe(frozen)
  await page.evaluate(() => document.querySelector('#app').__vue_app__.config.globalProperties.$router.push('/oc'))
  await expect(page.locator('.oc-page')).toBeVisible()
  await expect(page.locator('#play')).toHaveAttribute('aria-pressed', 'false')
  await page.locator('.oc-page nav a[href="#propiedades"]').click()
  await expect(page.locator('.oc-page #chapter-number')).toHaveText('03 / 04')
  await expect(page.locator('.oc-page .property')).toHaveCount(3)
  await page.screenshot({ path: 'test-results/oc-ionic-gallery.png' })
})

